module Find_users = struct
  type params = {
    org : Uuidm.t;
    email : string option;
    status : public_user_status option;
    min_balance : Decimal.t option;
    limit : int64;
  }

  type row = find_users_row

  let name = "FindUsers"

  let variants =
    [|
      "SELECT id, email, status, balance\n\
       FROM users\n\
       WHERE organization_id = $1\n\
      \  \n\
      \  \n\
      \  \n\
       ORDER BY email\n\
       LIMIT $2";
      "SELECT id, email, status, balance\n\
       FROM users\n\
       WHERE organization_id = $1\n\
      \   AND email ILIKE $2 \n\
      \  \n\
      \  \n\
       ORDER BY email\n\
       LIMIT $3";
      "SELECT id, email, status, balance\n\
       FROM users\n\
       WHERE organization_id = $1\n\
      \  \n\
      \   AND status = $2 \n\
      \  \n\
       ORDER BY email\n\
       LIMIT $3";
      "SELECT id, email, status, balance\n\
       FROM users\n\
       WHERE organization_id = $1\n\
      \   AND email ILIKE $2 \n\
      \   AND status = $3 \n\
      \  \n\
       ORDER BY email\n\
       LIMIT $4";
      "SELECT id, email, status, balance\n\
       FROM users\n\
       WHERE organization_id = $1\n\
      \  \n\
      \  \n\
      \   AND balance >= $2 \n\
       ORDER BY email\n\
       LIMIT $3";
      "SELECT id, email, status, balance\n\
       FROM users\n\
       WHERE organization_id = $1\n\
      \   AND email ILIKE $2 \n\
      \  \n\
      \   AND balance >= $3 \n\
       ORDER BY email\n\
       LIMIT $4";
      "SELECT id, email, status, balance\n\
       FROM users\n\
       WHERE organization_id = $1\n\
      \  \n\
      \   AND status = $2 \n\
      \   AND balance >= $3 \n\
       ORDER BY email\n\
       LIMIT $4";
      "SELECT id, email, status, balance\n\
       FROM users\n\
       WHERE organization_id = $1\n\
      \   AND email ILIKE $2 \n\
      \   AND status = $3 \n\
      \   AND balance >= $4 \n\
       ORDER BY email\n\
       LIMIT $5";
    |]

  let sql (p : params) =
    let b0 = match p.email with Some _ -> true | None -> false in
    let b1 = match p.status with Some _ -> true | None -> false in
    let b2 = match p.min_balance with Some _ -> true | None -> false in
    variants.((if b0 then 1 else 0) lor (if b1 then 2 else 0) lor if b2 then 4 else 0)

  let encode (p : params) =
    List.concat
      [
        [ Sqlml.Value.of_uuid p.org ];
        (match p.email with None -> [] | Some v -> [ Sqlml.Value.of_string v ]);
        (match p.status with None -> [] | Some v -> [ public_user_status_to_value v ]);
        (match p.min_balance with None -> [] | Some v -> [ Sqlml.Value.of_decimal v ]);
        [ Sqlml.Value.of_int64 p.limit ];
      ]

  let decode r : find_users_row =
    {
      id = (Sqlml.Row.option (Sqlml.Row.custom User_id.of_string)) r 0;
      email = (Sqlml.Row.option Sqlml.Row.string) r 1;
      status = (Sqlml.Row.option public_user_status_of_row) r 2;
      balance = (Sqlml.Row.option Sqlml.Row.decimal) r 3;
    }

  let columns = 4
  let cardinality = Sqlml.Query.Many
end

let find_users conn ~org ~limit ?email ?status ?min_balance () =
  Sqlml.fetch_all
    (module Find_users)
    conn
    { Find_users.org; email; status; min_balance; limit }

